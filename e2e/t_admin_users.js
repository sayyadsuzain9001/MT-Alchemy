const L = require('./lib');
(async () => {
  const stamp = Date.now();
  const trainer = `coach.${stamp}@mtalchemy.demo`;
  let { browser, page } = await L.start(1400, 1000);
  console.log('Admin creates a Trainer account');
  await L.signIn(page, 'admin@mtalchemy.demo', 'AlchemyAdmin!26');
  await L.open(page, '/admin/users', 5000);
  await L.expectText(page, 'learner@mtalchemy.demo', 'users list loads');
  await L.click(page, 'Add user', 'button', { wait: 1000 });
  await L.fill(page, 'Full name', 'Kavitha Rao');
  await L.fill(page, 'Email', trainer);
  await L.fill(page, 'Temporary password', 'Coach2026!x');
  await L.click(page, 'Create account', 'button', { wait: 4000 });
  await L.expectText(page, 'Trainer account created', 'trainer account created');
  await L.expectText(page, 'Admin portal', 'admin still signed in');
  await L.open(page, '/admin/organizations', 5000);
  await L.expectText(page, 'ABC Sdn Bhd', 'organizations list');
  await L.shot(page, 'admin_orgs');
  await browser.close();

  console.log('New trainer signs in, creates a draft course');
  ({ browser, page } = await L.start(1400, 1000));
  await L.signIn(page, trainer, 'Coach2026!x');
  await L.expectText(page, 'Welcome, Kavitha Rao', 'trainer dashboard for new account');
  await L.click(page, 'Courses', 'button', { exact: true, wait: 1000 });
  await L.click(page, 'Add or edit courses', 'button', { wait: 3000 });
  await L.click(page, 'Add course', 'button', { exact: true, wait: 1200 });
  await L.fill(page, 'Course title', `Resilience Basics ${stamp}`);
  await L.fill(page, 'Description', 'Bounce back from setbacks with practical tools.');
  await L.fill(page, 'Duration', '2 weeks');
  await L.fill(page, 'Modules — one per line', 'What resilience is\nDaily habits');
  await L.fill(page, 'Price (RM)', '199');
  await L.fill(page, 'Quiz questions', 'Is resilience a skill? | Yes | No | Yes');
  await L.click(page, 'Save course', 'button', { wait: 3500 });
  const course = (await L.fsList('courses')).find(c => c.title === `Resilience Basics ${stamp}`);
  L.check(course && course.status === 'Draft' && course.price === 199, 'trainer saved draft course to Firestore', JSON.stringify(course && [course.status, course.price]));
  await browser.close();

  console.log('Draft course hidden from public hub');
  ({ browser, page } = await L.start(1280, 900));
  await L.open(page, '/hub', 4000);
  const t = await L.text(page);
  L.check(!t.includes(`Resilience Basics ${stamp}`), 'draft not in catalogue');
  await browser.close();

  console.log('Admin suspends the trainer; sign-in is refused');
  ({ browser, page } = await L.start(1400, 1000));
  await L.signIn(page, 'admin@mtalchemy.demo', 'AlchemyAdmin!26');
  await L.open(page, '/admin/users', 5000);
  await L.fill(page, 'Search name or email', trainer);
  await page.waitForTimeout(800);
  await L.click(page, 'Suspend', 'button', { exact: true, wait: 2000 });
  await browser.close();
  ({ browser, page } = await L.start(1280, 900));
  await L.signIn(page, trainer, 'Coach2026!x');
  await L.expectText(page, 'suspended', 'suspended account blocked');
  await browser.close();

  console.log('Profile: learner updates details and password');
  ({ browser, page } = await L.start(1280, 900));
  await L.signIn(page, 'farah@example.com', 'AlchemyLearner!26');
  await L.open(page, '/profile', 5000);
  await L.fill(page, 'Job title', 'People Manager');
  await L.fill(page, 'Years of working experience', '9');
  await L.click(page, 'Save profile', 'button', { wait: 2500 });
  await L.expectText(page, 'Profile saved', 'profile saved');
  const farah = (await L.fsList('users')).find(x => x.email === 'farah@example.com');
  L.check(farah.jobTitle === 'People Manager' && farah.yearsWorking === '9', 'profile fields stored');
  await L.click(page, 'Change password', 'button', { wait: 1000 });
  await L.fill(page, 'Current password', 'AlchemyLearner!26');
  await L.fill(page, 'New password', 'Farah2026!new');
  await L.fill(page, 'Confirm new password', 'Farah2026!new');
  await L.click(page, 'Update password', 'button', { wait: 3000 });
  await L.expectText(page, 'Password updated', 'password changed');
  await browser.close();
  ({ browser, page } = await L.start(1280, 900));
  await L.signIn(page, 'farah@example.com', 'Farah2026!new');
  await L.expectText(page, 'Welcome, Farah', 'sign in with new password');
  await browser.close();
  console.log('FAILURES', L.failures());
})();
